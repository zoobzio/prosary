import type { OutputFile } from "@prosary/kit";

import { existsSync, readdirSync } from "node:fs";
import { basename, extname, join } from "node:path";

/** A component that renders in place of an element or a directive. */
export interface Override {
  /** The tag or directive it renders: the file's name, in kebab case. */
  name: string;
  /** The component file, absolute. */
  file: string;
}

/** `BlockQuote` to `block-quote`, `H2` to `h2`, `Callout` to `callout`. */
const kebab = (name: string): string => {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
};

/**
 * The overrides in a directory: every `.vue` file at its top level, named
 * for the tag or directive it renders. A directory that does not exist
 * holds none.
 *
 * @param directory - The absolute path of the overrides directory.
 */
export const scanOverrides = (directory: string): Override[] => {
  if (!existsSync(directory)) {
    return [];
  }
  return readdirSync(directory)
    .filter((entry) => extname(entry) === ".vue")
    .sort()
    .map((entry) => ({
      name: kebab(basename(entry, ".vue")),
      file: join(directory, entry),
    }));
};

/**
 * The `components` module: the overrides as the component map `Prose`
 * renders with, keyed by tag or directive. Its declaration checks every key
 * against the elements and directives the content builds, so an override
 * nothing renders fails `nuxt typecheck`.
 *
 * @param overrides - The overrides, from {@link scanOverrides}.
 */
export const componentsModule = (overrides: Override[]): OutputFile[] => {
  const names = overrides.map((override) => JSON.stringify(override.name));
  const imports = overrides.map(
    (override, index) =>
      `import override${index} from ${JSON.stringify(override.file)};`,
  );
  const entries = overrides.map(
    (override, index) =>
      `  ${JSON.stringify(override.name)}: override${index},`,
  );
  const keys = names.length === 0 ? "never" : `Known<${names.join(" | ")}>`;
  return [
    {
      path: "components.mjs",
      contents: [
        "// Generated by @prosary/nuxt. Do not edit by hand.",
        ...imports,
        `export const components = Object.freeze({\n${entries.join("\n")}\n});`,
        "",
      ].join("\n"),
    },
    {
      path: "components.d.mts",
      contents: [
        "// Generated by @prosary/nuxt. Do not edit by hand.",
        'import type { Component } from "vue";',
        'import type { Directive, Element } from "./index.mjs";',
        "/** An override names an element or a directive the content builds. */",
        "type Known<K extends Element | Directive> = K;",
        `export declare const components: Readonly<Record<${keys}, Component>>;`,
        "",
      ].join("\n"),
    },
  ];
};
