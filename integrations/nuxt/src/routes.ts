import type { OutputFile } from "@prosary/kit";

import { CONTENT, PREFIX } from "./constant";

/**
 * A prefix as the module mounts it: one leading slash, none trailing —
 * `/i18n` of `i18n/`. The root is the empty prefix, so the endpoints hang
 * straight off the app: `/content`.
 *
 * @param prefix - The module's `prefix` option, if any.
 */
export const normalizePrefix = (prefix: string = PREFIX): string => {
  const trimmed = prefix.trim().replace(/^\/+|\/+$/g, "");
  return trimmed === "" ? "" : `/${trimmed}`;
};

/**
 * Where the content documents are served from, under a prefix:
 * `{prefix}/content`, a document at `{prefix}/content/<locale>/<path>`.
 *
 * @param prefix - The prefix, from {@link normalizePrefix}.
 */
export const contentURL = (prefix: string): string => `${prefix}/${CONTENT}`;

/**
 * The `routes` module: where the module's endpoints are mounted, for the
 * runtime on both sides — the composable that fetches a document and the
 * server handlers that answer it read the one value, so they cannot drift
 * from each other or from the static files.
 *
 * @param prefix - The prefix, from {@link normalizePrefix}.
 */
export const routesModule = (prefix: string): OutputFile[] => {
  const routes = { prefix, content: contentURL(prefix) };
  return [
    {
      path: "routes.mjs",
      contents: [
        "// Generated by @prosary/nuxt. Do not edit by hand.",
        `export const routes = Object.freeze(${JSON.stringify(routes, null, 2)});`,
        "",
      ].join("\n"),
    },
    {
      path: "routes.d.mts",
      contents: [
        "// Generated by @prosary/nuxt. Do not edit by hand.",
        "export declare const routes: {",
        "  /** The prefix the module's endpoints are mounted under. */",
        "  readonly prefix: string;",
        "  /** Where the content documents are served from. */",
        "  readonly content: string;",
        "};",
        "",
      ].join("\n"),
    },
  ];
};
